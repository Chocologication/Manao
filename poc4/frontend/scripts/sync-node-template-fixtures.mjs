import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const templateIds = ['node-javascript-console', 'node-javascript-web', 'node-typescript-console', 'node-typescript-web'];
const fixtures = {};
for (const id of templateIds) {
  const extension = id.includes('typescript') ? 'ts' : 'js';
  const paths = ['package.json', 'pnpm-lock.yaml', '.npmrc', '.gitignore', 'README.md',
    ...(extension === 'ts' ? ['tsconfig.json'] : []), ...['app', 'app.test', 'main'].map(name => `src/${name}.${extension}`)];
  fixtures[id] = Object.fromEntries(paths.map(path => [path, readFileSync(new URL(`../../backend/src/main/resources/workspace-template-${id}/${path}`, import.meta.url), 'utf8')]));
}
const outputs = {
  'nodeTemplates.json': JSON.stringify(fixtures, null, 2) + '\n',
  'nodeTemplates.ts': '// Generated by scripts/sync-node-template-fixtures.mjs; mock-only project files.\n'
    + "import data from './nodeTemplates.json';\n"
    + 'export const NODE_TEMPLATE_FILES: Readonly<Record<string, Readonly<Record<string, string>>>> = data;\n',
};
for (const [name, content] of Object.entries(outputs)) {
  const target = fileURLToPath(new URL('../src/mocks/' + name, import.meta.url));
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content) throw new Error('Node template fixtures are stale');
  } else writeFileSync(target, content);
}
